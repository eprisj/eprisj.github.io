/* МАНУАЛ.
 *
 * Адресат конкретный: архитектор и исследователь искусства, который ведёт
 * издание, а не программист. Поэтому здесь нет ни строчки про базы данных и
 * кэши: всё, что осталось, это работа с источником, текстом, атрибуцией и
 * переводом.
 *
 * Главная ценность файла в примерах запросов. Они написаны под настоящие
 * задачи редакции (экспликация, каталожная запись, интервью, проверка
 * цитаты, перевод), а не выдуманы для красоты. Правя мануал, правьте прежде
 * всего их: абзацы объясняют, а запомнится образец.
 *
 * В видимом тексте нет длинных тире: правило всех текстов практики.
 */

export type Sample = {
  /** Задача одной строкой: зачем вообще этот запрос. */
  task: string;
  /** Как обычно пишут и почему это не работает. Необязательно. */
  bad?: string;
  /** Как написать, чтобы получить нужное. */
  good: string;
  why: string;
};

/** Пояснительная карточка: термин и его определение в одну фразу. */
export type Concept = { term: string; def: string };

/** Одна ветка алгоритма: путь и его шаги. kind решает, рисовать её как
 * тупиковую (bad) или рабочую (good). */
export type DiagramBranch = { label: string; kind: 'bad' | 'good'; steps: string[] };

/** Схема алгоритма: общая точка входа и несколько веток из неё. */
export type Diagram = { root: string; branches: DiagramBranch[] };

/** Иллюстрация: репродукция или её фрагмент.
 *
 * Атрибуция обязательна и лежит в самой структуре, а не в подписи, потому
 * что глава про права требует того же от читателя. `crop` заполняется, когда
 * показан фрагмент: зритель обязан понимать, что видит часть, а не вещь. */
export type Figure = {
  src: string;
  /** Что показано и зачем оно здесь. */
  caption: string;
  /** Автор, название, дата, собрание, права. */
  credit: string;
  /** Область оригинала, если это фрагмент. */
  crop?: string;
  alt: string;
};

/** Сравнение величин столбиками. Только для чисел, взятых из источника:
 * это иллюстрация к сверенным данным, а не украшение. */
export type Bars = {
  caption: string;
  /** Единица и дата свода: числа стареют, и читатель должен видеть, когда смотрели. */
  unit: string;
  items: { label: string; value: number; note?: string }[];
};

/** Строка таблицы источников: откуда брать данные и на каких условиях.
 * Адрес нужен буквальный: «поищите на сайте музея» это не источник. */
export type SourceRow = {
  name: string;
  /** Что оттуда реально можно взять. */
  gives: string;
  /** Условия: нужен ли ключ, есть ли предел выдачи, какая лицензия. */
  access: string;
  url: string;
};

export type Chapter = {
  slug: string;
  num: string;
  title: string;
  /** Одна строка о содержании: видна в оглавлении. */
  sense: string;
  body: string[];
  /** Пояснительные карточки терминов, если в главе вводится своя пара понятий. */
  concepts?: Concept[];
  /** Схема алгоритма, если в главе есть развилка путей, а не только текст. */
  diagram?: Diagram;
  /** Таблица источников: где брать данные по теме главы. */
  sources?: SourceRow[];
  /** Столбики со сверенными величинами. */
  bars?: Bars;
  /** Иллюстрации: репродукции и фрагменты. */
  figures?: Figure[];
  samples?: Sample[];
  /** Короткий список для проверки себя. */
  checklist?: string[];
};

