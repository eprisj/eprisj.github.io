/* КУРС: машина в искусствоведческой экспертизе.
 *
 * Отличается от мануала (см. src/codex/) не темой, а жанром и ставками.
 * Мануал это справочник практики: пришёл, взял приём, ушёл. Курс это
 * прохождение: модули идут в одном порядке, каждый опирается на предыдущий,
 * и у каждого есть задание, которое выполняется на своём материале.
 *
 * Предметная область выбрана не случайно. Экспертиза это единственная область
 * из всех, где мы работали с машиной, в которой результат подписывают. За
 * заключением стоят деньги, суд и репутация, а выдуманная сноска перестаёт
 * быть конфузом и становится профессиональной катастрофой. Поэтому весь курс
 * построен вокруг одной границы: что машина делает с ВАШИМ материалом и чего
 * она не имеет права делать вместо вас.
 *
 * В видимом тексте нет длинных тире: правило всех текстов практики.
 * Подсветка ==маркером== работает так же, как в мануале.
 */

